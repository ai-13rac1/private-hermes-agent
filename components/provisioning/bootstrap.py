"""Networkless, idempotent provisioning of separate SSH trust and data volumes."""
import os
import json
from pathlib import Path
from configure import configure
import subprocess
import tempfile
import hermes_yaml as yaml
from private_files import publish_default


def key(path):
    if not path.exists():
        with tempfile.TemporaryDirectory(prefix='private-hermes-ssh-') as folder:
            generated = Path(folder) / 'identity'
            subprocess.run(["/usr/bin/ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(generated)], check=True)
            publish_default(path, generated.read_bytes(), 0o600)
    public = path.with_name(path.name + '.pub')
    derived = subprocess.check_output(['/usr/bin/ssh-keygen', '-y', '-P', '', '-f', str(path)])
    if public.exists() and public.read_bytes().split()[:2] == derived.split()[:2]:
        return  # Preserve a complete matching public key and its operator comment.
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(derived)
            stream.flush()
            os.fsync(stream.fileno())
            os.replace(temporary, public)
        finally:
            temporary.unlink(missing_ok=True)


def initialize(data_root, home, defaults, auth, username):
    agent = data_root / "ssh/agent"
    executor = data_root / "ssh/executor"
    key(agent / "id_ed25519")
    key(executor / "ssh_host_ed25519_key")
    for path in agent.iterdir():
        os.chown(path, 10000, 10000)
        path.chmod(0o600)
    authorized = executor / "authorized_keys"
    authorized.write_bytes((agent / "id_ed25519.pub").read_bytes())
    authorized.chmod(0o644)
    known = agent / "known_hosts"
    known.write_bytes(b"[10.203.82.3]:2222 " + (executor / "ssh_host_ed25519_key.pub").read_bytes())
    os.chown(known, 10000, 10000)
    known.chmod(0o600)
    data = home
    config = data / "config.yaml"
    created = False
    if not config.exists():
        created = publish_default(config, defaults.read_bytes(), 0o600, owner=(10000, 10000))
    if not created:
        try:
            existing = yaml.safe_load(config.read_text())
            valid = (existing.get('terminal', {}).get('backend') == 'ssh'
                     and existing.get('model', {}).get('provider') == 'custom'
                     and existing.get('model', {}).get('base_url') == 'http://10.203.83.3:8337/v1')
        except Exception:
            valid = False
        if not valid:
            raise SystemExit('Hermes config must set terminal.backend=ssh, model.provider=custom, and model.base_url=http://10.203.83.3:8337/v1. Edit settings with: python3 scripts/stack.py compose run --rm --no-deps hermes-config set <key> <value>.')
        print('Hermes SSH/teep configuration validated.')
    # Credentials are generated by make init; this networkless step installs them
    # into the private profile before x402 provisioning and Hermes startup.
    document = yaml.safe_load(config.read_text())
    # Seed the native picker for existing profiles too; preserve operator catalogs.
    catalog = yaml.safe_load(defaults.read_text())['providers']['custom']
    provider = document.setdefault('providers', {}).setdefault('custom', catalog)
    preferred_model = os.environ.get('HERMES_DEFAULT_MODEL', '').strip()
    if preferred_model:
        document['model']['default'] = preferred_model
        if isinstance(provider.get('models'), dict):
            provider['models'].setdefault(preferred_model, {})
    configure(document, json.loads(auth.read_text()), username)
    with tempfile.NamedTemporaryFile(mode='w', dir=data, delete=False) as stream:
        temporary = Path(stream.name)
        yaml.safe_dump(document, stream, sort_keys=False)
    try:
        os.chown(temporary, 10000, 10000)
        temporary.chmod(0o600)
        os.replace(temporary, config)
    finally:
        temporary.unlink(missing_ok=True)
    print("Provisioned SSH identities and authenticated Hermes configuration.")
