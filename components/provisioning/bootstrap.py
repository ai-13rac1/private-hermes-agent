"""Networkless, idempotent provisioning of separate SSH trust and data volumes."""
import os
import json
from pathlib import Path
from configure import configure
import shutil
import subprocess
import tempfile
import hermes_yaml as yaml


def key(path):
    if not path.exists():
        subprocess.run(["/usr/bin/ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(path)], check=True)


def initialize(data_root, home, defaults, auth, username):
    agent = data_root / "ssh/agent"
    executor = data_root / "ssh/executor"
    key(agent / "id_ed25519")
    key(executor / "ssh_host_ed25519_key")
    for path in agent.iterdir():
        os.chown(path, 10000, 10000)
        path.chmod(0o600)
    authorized = executor / "authorized_keys"
    authorized.write_text((agent / "id_ed25519.pub").read_text())
    authorized.chmod(0o644)
    known = agent / "known_hosts"
    known.write_text("[10.203.82.3]:2222 " + (executor / "ssh_host_ed25519_key.pub").read_text())
    os.chown(known, 10000, 10000)
    known.chmod(0o600)
    data = home
    config = data / "config.yaml"
    if not config.exists():
        shutil.copyfile(defaults, config)
        os.chown(config, 10000, 10000)
        config.chmod(0o600)
    else:
        try:
            existing = yaml.safe_load(config.read_text())
            valid = (existing.get('terminal', {}).get('backend') == 'ssh'
                     and existing.get('model', {}).get('provider') == 'custom'
                     and existing.get('model', {}).get('base_url') == 'http://10.203.83.3:8337/v1')
        except Exception:
            valid = False
        if not valid:
            raise SystemExit('Hermes config must set terminal.backend=ssh, model.provider=custom, and model.base_url=http://10.203.83.3:8337/v1. Edit settings with: docker compose run --rm setup config set <key> <value>.')
        print('Hermes SSH/teep configuration validated.')
    # Credentials are generated by make init; this networkless step installs them
    # into the private profile before x402 provisioning and Hermes startup.
    document = yaml.safe_load(config.read_text())
    configure(document, json.loads(auth.read_text()), username)
    with tempfile.NamedTemporaryFile(mode='w', dir=data, delete=False) as stream:
        temporary = Path(stream.name)
        yaml.safe_dump(document, stream, sort_keys=False)
    try:
        os.chown(temporary, 10000, 10000)
        temporary.chmod(0o600)
        os.replace(temporary, config)
    finally:
        temporary.unlink(missing_ok=True)
    print("Provisioned SSH identities and authenticated Hermes configuration.")
